package com.OdysseyAi.demo.travel.service;

import com.OdysseyAi.demo.travel.dto.RouteData;
import org.springframework.stereotype.Service;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

@Service
public class TransportCostService {

    private static final BigDecimal ZERO =
            BigDecimal.ZERO.setScale(2, RoundingMode.HALF_UP);

    /*
     * Estimated fallback prices when Google does not provide
     * an actual transit fare.
     *
     * These are deliberately simple estimates for now.
     */
    private static final BigDecimal DRIVE_COST_PER_KM =
            new BigDecimal("15.00");

    private static final BigDecimal TRANSIT_BASE_COST =
            new BigDecimal("20.00");

    private static final BigDecimal TRANSIT_COST_PER_KM =
            new BigDecimal("3.00");


    /**
     * Calculates the total transport cost for the ACTUAL itinerary.
     *
     * The same route segment can occur multiple times in the itinerary,
     * so we calculate the cost once for every occurrence.
     *
     * Example:
     *
     * Hotel -> Temple
     * Temple -> Beach
     * Beach -> Temple
     *
     * The Temple -> Beach and Beach -> Temple journeys are counted
     * separately.
     *
     * For each journey we choose the cheapest available transport mode.
     */
    public BigDecimal calculateTransportCost(
            List<String> itineraryLocations,
            List<RouteData> routeData
    ) {

        if (itineraryLocations == null
                || itineraryLocations.size() < 2
                || routeData == null
                || routeData.isEmpty()) {

            return ZERO;
        }


        /*
         * Build a lookup:
         *
         * origin + destination
         *        ->
         * route options
         *
         * Example:
         *
         * Goa Hotel -> Temple
         *      DRIVE
         *      TRANSIT
         */
        Map<String, Map<String, RouteData>> routeLookup =
                buildRouteLookup(routeData);


        BigDecimal totalCost = ZERO;


        /*
         * Walk through the itinerary in the exact order
         * generated by the AI.
         */
        for (int i = 0; i < itineraryLocations.size() - 1; i++) {

            String origin =
                    clean(itineraryLocations.get(i));

            String destination =
                    clean(itineraryLocations.get(i + 1));


            /*
             * Ignore invalid / duplicate consecutive locations.
             */
            if (origin.isBlank()
                    || destination.isBlank()
                    || origin.equalsIgnoreCase(destination)) {

                continue;
            }


            String pairKey =
                    buildPairKey(
                            origin,
                            destination
                    );


            Map<String, RouteData> options =
                    routeLookup.get(pairKey);


            /*
             * No route was successfully calculated for this leg.
             * We cannot invent a route cost.
             */
            if (options == null || options.isEmpty()) {
                continue;
            }


            BigDecimal cheapestCost =
                    findCheapestRouteCost(options);


            if (cheapestCost != null) {

                totalCost =
                        totalCost.add(
                                cheapestCost
                        );
            }
        }


        return totalCost.setScale(
                2,
                RoundingMode.HALF_UP
        );
    }


    /**
     * Backward-compatible overload.
     *
     * This is useful if another part of the application still calls:
     *
     * calculateTransportCost(routeData)
     *
     * It calculates the cheapest cost from every supplied route option,
     * but it cannot account for repeated itinerary legs.
     *
     * Your selected-itinerary flow should use the method above.
     */
    public BigDecimal calculateTransportCost(
            List<RouteData> routeData
    ) {

        if (routeData == null || routeData.isEmpty()) {
            return ZERO;
        }

        BigDecimal total = ZERO;

        /*
         * Group by directional pair so DRIVE + TRANSIT are treated
         * as alternatives rather than being added together.
         */
        Map<String, Map<String, RouteData>> routeLookup =
                buildRouteLookup(routeData);


        for (Map<String, RouteData> options
                : routeLookup.values()) {

            BigDecimal cheapestCost =
                    findCheapestRouteCost(options);

            if (cheapestCost != null) {

                total =
                        total.add(
                                cheapestCost
                        );
            }
        }

        return total.setScale(
                2,
                RoundingMode.HALF_UP
        );
    }


    /**
     * Creates:
     *
     * origin+destination
     * ->
     * travelMode+RouteData
     */
    private Map<String, Map<String, RouteData>> buildRouteLookup(
            List<RouteData> routeData
    ) {

        Map<String, Map<String, RouteData>> lookup =
                new HashMap<>();


        for (RouteData route : routeData) {

            if (route == null) {
                continue;
            }

            String origin =
                    clean(route.getOrigin());

            String destination =
                    clean(route.getDestination());

            String travelMode =
                    clean(route.getTravelMode());


            if (origin.isBlank()
                    || destination.isBlank()
                    || travelMode.isBlank()) {

                continue;
            }


            String pairKey =
                    buildPairKey(
                            origin,
                            destination
                    );


            lookup
                    .computeIfAbsent(
                            pairKey,
                            key -> new HashMap<>()
                    )
                    .put(
                            travelMode.toUpperCase(),
                            route
                    );
        }


        return lookup;
    }


    /**
     * Finds the cheapest transport option for one itinerary leg.
     *
     * DRIVE and TRANSIT are alternatives.
     * We never add both together.
     */
    private BigDecimal findCheapestRouteCost(
            Map<String, RouteData> options
    ) {

        BigDecimal cheapest =
                null;


        for (RouteData route : options.values()) {

            BigDecimal cost =
                    calculateRouteCost(
                            route
                    );


            if (cost == null) {
                continue;
            }


            if (cheapest == null
                    || cost.compareTo(cheapest) < 0) {

                cheapest = cost;
            }
        }


        return cheapest;
    }


    /**
     * Calculates the cost for one specific route.
     *
     * Priority:
     *
     * 1. Use Google-provided fare when available.
     * 2. For DRIVE, estimate using distance.
     * 3. For TRANSIT, estimate using base fare + distance.
     */
    private BigDecimal calculateRouteCost(
            RouteData route
    ) {

        if (route == null) {
            return null;
        }


        /*
         * If Google supplied an actual fare,
         * always prefer it.
         */
        if (route.getFare() != null) {

            return route.getFare()
                    .setScale(
                            2,
                            RoundingMode.HALF_UP
                    );
        }


        Long distanceMeters =
                route.getDistanceMeters();


        if (distanceMeters == null
                || distanceMeters < 0) {

            return null;
        }


        BigDecimal distanceKm =
                BigDecimal.valueOf(
                                distanceMeters
                        )
                        .divide(
                                BigDecimal.valueOf(1000),
                                2,
                                RoundingMode.HALF_UP
                        );


        String mode =
                clean(route.getTravelMode())
                        .toUpperCase();


        /*
         * DRIVE fallback estimate.
         */
        if ("DRIVE".equals(mode)) {

            return distanceKm
                    .multiply(
                            DRIVE_COST_PER_KM
                    )
                    .setScale(
                            2,
                            RoundingMode.HALF_UP
                    );
        }


        /*
         * TRANSIT fallback estimate.
         */
        if ("TRANSIT".equals(mode)) {

            return TRANSIT_BASE_COST
                    .add(
                            distanceKm.multiply(
                                    TRANSIT_COST_PER_KM
                            )
                    )
                    .setScale(
                            2,
                            RoundingMode.HALF_UP
                    );
        }


        /*
         * Unknown transport mode.
         */
        return null;
    }


    private String buildPairKey(
            String origin,
            String destination
    ) {

        return normalize(origin)
                + "||"
                + normalize(destination);
    }


    private String normalize(
            String value
    ) {

        return clean(value)
                .toLowerCase()
                .replaceAll(
                        "\\s+",
                        " "
                );
    }


    private String clean(
            String value
    ) {

        return value == null
                ? ""
                : value.trim();
    }
}
